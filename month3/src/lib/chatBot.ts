import { BUSINESS_DATA } from '../data/business';

export interface IntentResponse {
  matched: boolean;
  reply: string | null;
  intentName?: string;
}

/**
 * Локальный rule-based классификатор интентов.
 * Работает мгновенно на клиенте/сервере без обращения к сети и LLM.
 * Если совпадений нет — возвращает matched: false (fallback).
 */
export function getBotResponse(userText: string): IntentResponse {
  const query = userText.toLowerCase().trim();

  // 1. Приветствие
  if (/^(привет|здравствуй|добрый день|добрый вечер|доброе утро|салют|хай|hello|hi)/i.test(query)) {
    return {
      matched: true,
      intentName: 'greeting',
      reply: `Здравствуйте! Я виртуальный ассистент ${BUSINESS_DATA.shortName}. Могу подсказать цены на сервис, график работы, адрес, условия гарантии или записать вас на диагностику и тест-драйв.`
    };
  }

  // 2. График работы / часы
  if (/(график|часы работы|режим|когда работаете|до скольки|во сколько открываетесь|время работы)/i.test(query)) {
    return {
      matched: true,
      intentName: 'working_hours',
      reply: `Наш сервисный центр и шоурум открыты:\n• Будни: ${BUSINESS_DATA.workingHours.weekdays}\n• Выходные: ${BUSINESS_DATA.workingHours.weekends}\n• Онлайн-поддержка: ${BUSINESS_DATA.workingHours.supportOnline}`
    };
  }

  // 3. Адрес, где находитесь, контакты
  if (/(где находитесь|адрес|как доехать|где вы|контакт|телефон|номер|локаци|на карте)/i.test(query)) {
    return {
      matched: true,
      intentName: 'contacts',
      reply: `Наш адрес: ${BUSINESS_DATA.address}\n\nТелефон: ${BUSINESS_DATA.phone}\nTelegram: ${BUSINESS_DATA.telegram}\nWhatsApp: ${BUSINESS_DATA.whatsapp}\nБудем рады видеть вас!`
    };
  }

  // 4. Услуги и цены
  if (/(услуг|цен|прайс|сколько стоит|диагностик|замен.*масл|колодк|шиномонтаж|детейлинг)/i.test(query)) {
    const list = BUSINESS_DATA.services.map(s => `• ${s.name} — ${s.price} (${s.time})`).join('\n');
    return {
      matched: true,
      intentName: 'services_pricing',
      reply: `Популярные услуги ${BUSINESS_DATA.shortName}:\n\n${list}\n\nЧтобы записаться на удобное время, напишите ваш номер телефона или нажмите кнопку записи на сайте.`
    };
  }

  // 5. Электромобили / Tesla / Zeekr
  if (/(электрокар|электромобил|tesla|тесла|zeekr|taycan|батаре|зарядк)/i.test(query)) {
    return {
      matched: true,
      intentName: 'ev_service',
      reply: `Да, мы специализируемся на диагностике, русификации и обслуживании электромобилей (Tesla Model 3/Y/S/X, Porsche Taycan, Zeekr, Li Auto). Стоимость комплексной компьютерной проверки EV — от 6 000 ₽.`
    };
  }

  // 6. Гарантия
  if (/(гаранти|надежност|качество)/i.test(query)) {
    return {
      matched: true,
      intentName: 'guarantee',
      reply: `${BUSINESS_DATA.guarantee}\nИспользуем только сертифицированное дилерское оборудование и оригинальные комплектующие.`
    };
  }

  // 7. Оплата и рассрочка
  if (/(оплат|картой|рассрочк|безнал|нал|сбп|кредит)/i.test(query)) {
    const methods = BUSINESS_DATA.paymentMethods.map(m => `• ${m}`).join('\n');
    return {
      matched: true,
      intentName: 'payment',
      reply: `Доступные способы оплаты:\n\n${methods}`
    };
  }

  // 8. Тест-драйв / Трейд-ин
  if (/(тест.?драйв|трейд.?ин|trade.?in|обмен.*авто|оценк)/i.test(query)) {
    return {
      matched: true,
      intentName: 'test_drive_tradein',
      reply: `Тест-драйв любого автомобиля из каталога и оценка по Trade-In проводятся бесплатно! Оценка занимает всего 30 минут. Хотите выбрать модель для тест-драйва?`
    };
  }

  // 9. Подвеска / амортизаторы / стойки / стук / люфт
  if (/(подвеск|амортизатор|стойк|стук| люфт | сайлентблок|шаров|направляющ|пружин|рессор|стабилизатор)/i.test(query)) {
    return {
      matched: true,
      intentName: 'suspension',
      reply: `Стуки и люфты в подвеске — одна из самых частых причин обращения. Проводим полную диагностику подвески на стенде (60 точек): амортизаторы, стойки, сайлентблоки, шаровые опоры. Стоимость диагностики — от 2 500 ₽, выполняется за 40 минут.`
    };
  }

  // 10. Аккумулятор / батарея / сел / не заводится
  if (/(аккумулятор|аккум|батарея|севш|не заводит|севший|заряд.*аккум)/i.test(query)) {
    return {
      matched: true,
      intentName: 'battery',
      reply: `Проверим состояние аккумулятора и зарядной системы тестером за 15 минут. Подберём и заменим АКБ на совместимую с гарантией 24 месяца. Стоимость диагностики — от 1 500 ₽, замена АКБ — от 2 000 ₽ (с работой).`
    };
  }

  // 11. Кондиционер / климат / обогрев / запах
  if (/(кондиционер|кондиц|климат|обогрев|запах.*салон|освежит|холод.*тёпл|тёпл.*холод|компрессор.*кондиц)/i.test(query)) {
    return {
      matched: true,
      intentName: 'climate',
      reply: `Диагностика и заправка кондиционера, замена компрессора, чистка испарителя — все виды работ по климат-системе. Стоимость заправки — от 3 500 ₽, комплексная диагностика — от 2 000 ₽.`
    };
  }

  // 12. Свечи / зажигание / троит / вибрация
  if (/(свеч|зажиган|троит|вибрац|пропуск|пропуски зажиган|прострел|пропуск цилиндр)/i.test(query)) {
    return {
      matched: true,
      intentName: 'ignition',
      reply: `Пропуски зажигания и вибрация могут указывать на износ свечей, высоковольтных проводов или катушек зажигания. Диагностика зажигания — от 2 000 ₽, замена свечей — от 1 500 ₽.`
    };
  }

  // 13. ГРМ / ремень / цепь
  if (/(грм|ремень.*грм|цепь.*грм|газораспредел|газораспр|натяжител|метки.*грм)/i.test(query)) {
    return {
      matched: true,
      intentName: 'timing_belt',
      reply: `Замена ремня/цепи ГРМ с натяжителями и роликами — один из ключевых видов ТО. Интервал замены обычно 60 000–100 000 км. Стоимость работ — от 6 000 ₽, с комплектом запчастей — по запросу.`
    };
  }

  // 14. Кузов / вмятина / покраска / ржавчина
  if (/(кузов|вмятин|покрас|ржавчин|скол|царапин|ЛКП|лакокрас|коррозия|хром)/i.test(query)) {
    return {
      matched: true,
      intentName: 'bodywork',
      reply: `Выполняем покраску элементов кузова, удаление вмятин PDR, полировку и нанесение керамического покрытия. Красим в камере с контролем температуры и влажности. Стоимость покраски отдельного элемента — от 8 000 ₽, детейлинг — от 12 000 ₽.`
    };
  }

  // 15. Датчики / ошибки / электроника / парктроник / камера
  if (/(датчик|ошибк|парктроник|камера.*задня|камера.*вид|check.?engine|бортовой компьютер|электроник|датчик.*абс|датчик.*расход)/i.test(query)) {
    return {
      matched: true,
      intentName: 'sensors',
      reply: `Компьютерная диагностика сканерами дилерского уровня считывает все коды ошибок по блокам ESP, ABS, двигателя и кузовной электроники. Стоимость полной диагностики — от 3 500 ₽ (45 минут), после чего выдаём отчёт и рекомендации.`
    };
  }

  // 16. Коробка передач / АКПП / МКПП
  if (/(коробк|акпп|мкпп|кпп|передач|пинок|задержк.*переключ|пробуксов|масло.*коробк)/i.test(query)) {
    return {
      matched: true,
      intentName: 'transmission',
      reply: `Диагностика и обслуживание АКПП/МКПП: замена трансмиссионного масла, фильтров, блок клапанов. Проводим адаптацию АКПП после ремонта. Стоимость диагностики — от 3 000 ₽, замена масла в АКПП — от 5 000 ₽.`
    };
  }

  // 17. Страховка / ОСАГО / КАСКО
  if (/(страховк|осаго|каско|страхов|полис|страхов.*компани)/i.test(query)) {
    return {
      matched: true,
      intentName: 'insurance',
      reply: `При оформлении тест-драйва мы предоставляем полное страхование ОСАГО на весь период эксплуатации. Для консультации по КАСКО свяжитесь с нашим менеджером: ${BUSINESS_DATA.phone}.`
    };
  }

  // 18. Запчасти / расходники / комплектующие
  if (/(запчаст|расходник|комплектующ|оригинал|аналог|каталожн|артикул|поставк)/i.test(query)) {
    return {
      matched: true,
      intentName: 'parts',
      reply: `Работаем с оригинальными запчастями и проверенными аналогами (Lemförder, TRW, Bosch, SKF). Подберём по VIN-номеру и доставим за 1–3 рабочих дня.`
    };
  }

  // 19. Эвакуатор / поломка на дороге
  if (/(эвакуатор|эвакуац|на дороге|встал.*дорог|вызвать.*евакуатор|буксир)/i.test(query)) {
    return {
      matched: true,
      intentName: 'tow_truck',
      reply: `При поломке на дороге мы организуем вызов эвакуатора и экстренный приём в сервисе. Телефон круглосуточной поддержки: ${BUSINESS_DATA.phone}.`
    };
  }

  // 20. Выбросы / выхлоп / катализатор / сажевый фильтр
  if (/(выхлоп|глушител|каталит|сажев|проставк|проблем.*выхлоп|запах.*выхлоп|розовый.*выхлоп|дым)/i.test(query)) {
    return {
      matched: true,
      intentName: 'exhaust',
      reply: `Диагностика и ремонт системы выпуска: замена глушителя, удаление/замена катализатора, обслуживание сажевого фильтра (DPF/FAP). Стоимость диагностики — от 2 500 ₽.`
    };
  }

  // 21. Предпродажная подготовка / подготовка к продаже
  if (/(предпродаж|подготов.*продаж|продать.*авто|оформлен.*продаж|продать)/i.test(query)) {
    return {
      matched: true,
      intentName: 'pre_sale',
      reply: `Предпродажная подготовка включает полную диагностику (120 точек), детейлинг кузова и салона, замену расходников — всё в одном пакете. Это повышает стоимость автомобиля при продаже.`
    };
  }

  // 22. Шиномонтаж / сезонная замена шин / хранение шин
  if (/(шиномонтаж|сезон.*шин|сезон.*колес|хранени.*шин|сезонн.*хранени|переобуть)/i.test(query)) {
    return {
      matched: true,
      intentName: 'tire_season',
      reply: `Сезонный шиномонтаж на стендах Hunter: балансировка, вулканизация, бережная мойка колес. Доступно сезонное хранение шин в специальной камере хранения. Стоимость шиномонтажа — от 2 800 ₽.`
    };
  }

  // 23. Салон / чистка / химчистка / запах / обивка
  if (/(салон.*чист|химчистк|чистк.*салон|обивк|интерьер|запах.*внутр|одориз|аромат|ароматиз|протирк)/i.test(query)) {
    return {
      matched: true,
      intentName: 'interior',
      reply: `Химчистка салона (ткань + кожа): удаление пятен, запахов, антибактериальная обработка. Стоимость — от 4 500 ₽, экпресс-химчистка — от 2 500 ₽.`
    };
  }

  // 24. Расход топлива / экономия / чип-тюнинг / прошивка
  if (/(расход.*топлив|эконом.*топлив|аппаратн|чип|прошивк|тюнинг|эбу|эбр)/i.test(query)) {
    return {
      matched: true,
      intentName: 'tuning_fuel',
      reply: `Проведём диагностику системы топливоподачи и проверим фактический расход под нагрузкой. Чип-тюнинг и прошивка ЭБУ доступны для ряда моделей — уточним возможность и стоимость по вашему автомобилю.`
    };
  }

  // 25. Выбор автомобиля / какую машину выбрать / рекомендация
  if (/(какую.*машин|какой.*авто|какой.*автомобил|выбор.*авто|рекомендац.*авто|подбер.*машин|что выбрать|лучш.*авто)/i.test(query)) {
    return {
      matched: true,
      intentName: 'car_selection',
      reply: `Наши эксперты помогут подобрать автомобиль под ваш бюджет и потребности. Запишитесь на бесплатную консультацию в шоурум — ${BUSINESS_DATA.address}.`
    };
  }

  // 26. Удалённая диагностика / диагностика на расстоянии
  if (/(удалённ|дистанц|удален.*диагност|дистанц.*диагност|онлайн.*диагност)/i.test(query)) {
    return {
      matched: true,
      intentName: 'remote_diagnostics',
      reply: `Для первичной удалённой консультации скиньте нам фото/видео неисправности в чат или WhatsApp (${BUSINESS_DATA.whatsapp}). Для полной диагностики потребуется визит в сервис.`
    };
  }

  // Fallback (не подошел ни один статичный интент -> идем в базу FAQ / Gemini)
  return {
    matched: false,
    reply: null
  };
}
